package com.web.java_dsa.javalearn.data_types;

public class Primitive {
    public static void main(String[] args) {
        System.out.println("Primitiv data types of size");
        System.out.println("Byte \t=> " + Byte.SIZE);
        System.out.println("Short \t=> " + Short.SIZE);
        System.out.println("Integer \t=> " + Integer.SIZE);
        System.out.println("Long \t=> " + Long.SIZE);
        System.out.println("Double \t=> " + Double.SIZE);
        System.out.println("Float \t=> " + Float.SIZE);
        System.out.println("Character \t=> " + Character.SIZE);

        System.out.println("------------------------------");
        System.out.println("Primitive data types ni nechta bayt joy olishi");
        System.out.println("Byte \t=> " + Byte.BYTES);
        System.out.println("Short \t=> " + Short.BYTES);
        System.out.println("Integer \t=> " + Integer.BYTES);
        System.out.println("Long \t=> " + Long.BYTES);
        System.out.println("Double \t=> " + Double.BYTES);
        System.out.println("Float \t=> " + Float.BYTES);
        System.out.println("Character \t=> " + Character.BYTES);

        System.out.println("---------------------------");
        System.out.println("Byte min and max values");
        System.out.println("Byte \t=> " + Byte.MAX_VALUE);
        System.out.println("Byte \t=> " + Byte.MIN_VALUE);

        System.out.println("------------------------------");

        System.out.println("Short max and min values");
        System.out.println("Short \t=> " + Short.MAX_VALUE);
        System.out.println("Short \t=> " + Short.MIN_VALUE);

        System.out.println("------------------------------");

        System.out.println("Integer min and max values");
        System.out.println("Integer \t=> " + Integer.MAX_VALUE);
        System.out.println("Integer \t=> " + Integer.MIN_VALUE);

        System.out.println("------------------------------");

        System.out.println("Long min and max values");
        System.out.println("Long \t=> " + Long.MAX_VALUE);
        System.out.println("Long \t=> " + Long.MIN_VALUE);

        System.out.println("------------------------------");

        System.out.println("Double min and max values");
        System.out.println("Double \t=> " + Double.MAX_VALUE);
        System.out.println("Double \t=> " + Double.MIN_VALUE);

        System.out.println("------------------------------");

        System.out.println("Float min and max values");
        System.out.println("Float \t=> " + Float.MAX_VALUE);
        System.out.println("Float \t=> " + Float.MIN_VALUE);

        System.out.println("------------------------------");

        System.out.println("Character min and max values");
        System.out.println("Character \t=> " + Character.MAX_VALUE);
        System.out.println("Character \t=> " + Character.MIN_VALUE);
    }
}
